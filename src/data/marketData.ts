function generateCandles(basePrice: number, count: number = 30, volatility: number = 0.015) {
  const candles = [];
  let currentClose = basePrice * (1 - volatility * (count / 3));
  const now = new Date('2026-11-09T18:00:00Z').getTime();

  for (let i = 0; i < count; i++) {
    const time = new Date(now - (count - i) * 3600 * 1000 * 4).toLocaleTimeString([], {
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
    const delta = (Math.random() - 0.48) * volatility * currentClose;
    const open = Number(currentClose.toFixed(2));
    const close = Number(Math.max(1, open + delta).toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * volatility * 0.8 * currentClose).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * volatility * 0.8 * currentClose).toFixed(2));
    const volume = Math.floor(Math.random() * 5000000 + 1000000);

    candles.push({ time, open, high, low, close, volume });
    currentClose = close;
  }
  return candles;
}

function generateSparkline(candles: ReturnType<typeof generateCandles>): number[] {
  return candles.map((c) => c.close);
}

